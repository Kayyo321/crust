use std::collections::{BTreeMap, HashSet};
use std::fmt::Write;

pub struct codegen<'a> {
    prog: &'a program,
    globals_out: String,
    funcs_out: String,
    /// External declarations, by symbol.
    decls: BTreeMap<String, String>,
    defined: HashSet<String>,
    used_strings: HashSet<u32>,
    trap_msgs: Vec<String>,
    need_trap: bool,
    intrinsics: BTreeMap<String, String>,
}

pub fn quote_sym(s: &str) -> String {
    let ok = !s.is_empty()
        && s.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | '$' | '-'))
        && !s.chars().next().unwrap().is_ascii_digit();
    if ok { format!("@{s}") } else { format!("@\"{}\"", s.replace('"', "\\22")) }
}

fn llvm_bytes(b: &[u8]) -> String {
    let mut s = String::from("c\"");
    for &c in b {
        if c.is_ascii_graphic() && c != b'"' && c != b'\\' || c == b' ' {
            s.push(c as char);
        } else {
            let _ = write!(s, "\\{c:02X}");
        }
    }
    s.push('"');
    s
}

fn mem_ty(t: type_id) -> String {
    if is_aggregate(t) || is_function(t) {
        format!("[{} x i8]", size_of(t))
    } else {
        llvm_scalar(t).to_string()
    }
}

pub fn float_lit(v: f64, t: type_id) -> String {
    match kind(t) {
        TypeKindFloat(FloatKindFloat) => format!("0x{:016X}", (v as f32 as f64).to_bits()),
        TypeKindFloat(FloatKindLongDouble) => {
            let b = f64_to_x87(v);
            let mut s = String::from("0xK");
            for i in (0..10).rev() {
                let _ = write!(s, "{:02X}", b[i]);
            }
            s
        }
        _ => format!("0x{:016X}", v.to_bits()),
    }
}

pub fn emit_module(prog: &program, bodies: &[body], source: &str) -> String {
    let mut cg = codegen {
        prog,
        globals_out: String::new(),
        funcs_out: String::new(),
        decls: BTreeMap::new(),
        defined: HashSet::new(),
        used_strings: HashSet::new(),
        trap_msgs: Vec::new(),
        need_trap: false,
        intrinsics: BTreeMap::new(),
    };
    for g in &prog.globals {
        if g.defined
            && (!g.is_func
                || bodies.iter().any(|b| prog.globals[b.func as usize].symbol == g.symbol))
        {
            cg.defined.insert(g.symbol.clone());
        }
    }
    for (i, g) in prog.globals.iter().enumerate() {
        if !g.is_func && g.defined && g.imported_from.is_none() {
            cg.emit_global(i as global_id);
        }
    }
    for b in bodies {
        cg.emit_function(b);
    }
    let mut out = String::new();
    let _ = writeln!(out, "; Generated by crust {} from {}", env!("CARGO_PKG_VERSION"), source);
    out.push_str(
        "target datalayout = \"e-m:e-p270:32:32-p271:32:32-p272:64:64-i64:64-i128:128-f80:128-n8:16:32:64-S128\"\n",
    );
    out.push_str("target triple = \"x86_64-pc-linux-gnu\"\n\n");
    let strings: Vec<u32> = {
        let mut v: Vec<u32> = cg.used_strings.iter().copied().collect();
        v.sort();
        v
    };
    for s in strings {
        let lit = &prog.strings[s as usize];
        let et = llvm_scalar(match kind(lit.ty) {
            TypeKindArray(e, _) => e.ty,
            _ => char_(),
        });
        let mut units = lit.units.clone();
        units.push(0);
        let body = if et == "i8" {
            let b: Vec<u8> = units.iter().map(|u| *u as u8).collect();
            llvm_bytes(&b)
        } else {
            format!(
                "[{}]",
                units.iter().map(|u| format!("{et} {}", *u as i64)).collect::<Vec<_>>().join(", ")
            )
        };
        let _ = writeln!(
            out,
            "@.str.{s} = private unnamed_addr constant [{} x {et}] {body}, align {}",
            units.len(),
            lit.encoding.unit_size()
        );
    }
    for (i, m) in cg.trap_msgs.iter().enumerate() {
        let _ = writeln!(
            out,
            "@.trapmsg.{i} = private unnamed_addr constant [{} x i8] {}",
            m.len(),
            llvm_bytes(m.as_bytes())
        );
    }
    out.push_str(&cg.globals_out);
    out.push('\n');
    out.push_str(&cg.funcs_out);
    if cg.need_trap {
        out.push_str(
            "\ndefine internal void @crust.trap(ptr %msg, i64 %len) noreturn cold noinline nounwind {\n  \
             %1 = call i64 @write(i32 2, ptr %msg, i64 %len)\n  call void @abort()\n  unreachable\n}\n",
        );
        if !cg.defined.contains("write") {
            cg.decls
                .entry("write".into())
                .or_insert_with(|| "declare i64 @write(i32, ptr, i64)".into());
        }
        if !cg.defined.contains("abort") {
            cg.decls
                .entry("abort".into())
                .or_insert_with(|| "declare void @abort() noreturn".into());
        }
    }
    out.push('\n');
    for d in cg.decls.values() {
        out.push_str(d);
        out.push('\n');
    }
    for d in cg.intrinsics.values() {
        out.push_str(d);
        out.push('\n');
    }
    out
}

/// The ABI-lowered signature of a function type.
pub struct lowered_sig {
    pub ret: ArgKind,
    pub params: Vec<ArgKind>,
    pub variadic: bool,
}

pub fn lower_sig(ft: &func_type) -> lowered_sig {
    let ret = classify(ft.ret.ty);
    let sret = matches!(ret, ArgKindMemory);
    let ptys: Vec<type_id> = ft.params.iter().map(|p| p.ty).collect();
    lowered_sig { params: classify_params(&ptys, sret), ret, variadic: ft.variadic }
}

impl lowered_sig {
    pub fn param_types(&self, ft: &func_type) -> Vec<String> {
        let mut v = Vec::new();
        if matches!(self.ret, ArgKindMemory) {
            v.push(format!(
                "ptr sret([{} x i8]) align {}",
                size_of(ft.ret.ty),
                align_of(ft.ret.ty)
            ));
        }
        for (k, p) in self.params.iter().zip(&ft.params) {
            match k {
                ArgKindIgnore => {}
                ArgKindDirect(t, ext) => v.push(match ext {
                    Some(e) => format!("{t} {e}"),
                    None => t.clone(),
                }),
                ArgKindExpand(ps) => v.extend(ps.iter().map(|p| p.0.clone())),
                ArgKindMemory => v.push(format!(
                    "ptr byval([{} x i8]) align {}",
                    size_of(p.ty),
                    align_of(p.ty).max(8)
                )),
            }
        }
        v
    }

    pub fn ret_type(&self) -> String {
        let r = ret_llvm(&self.ret);
        match &self.ret {
            ArgKindDirect(t, Some(e)) => format!("{e} {t}"),
            _ => r,
        }
    }

    pub fn fn_type(&self, ft: &func_type) -> String {
        let mut ps = self
            .param_types(ft)
            .iter()
            .map(|p| p.split(' ').next().unwrap().to_string())
            .collect::<Vec<_>>();
        if self.variadic {
            ps.push("...".into());
        }
        format!("{} ({})", ret_llvm(&self.ret), ps.join(", "))
    }
}

impl codegen<'_> {
    fn global_sym(&mut self, g: global_id) -> String {
        let gd = &self.prog.globals[g as usize];
        let s = gd.symbol.clone();
        if !self.defined.contains(&s) && !self.decls.contains_key(&s) {
            let decl = if gd.is_func {
                let ft = func_of(gd.ty.ty).unwrap();
                let sig = lower_sig(&ft);
                let mut ps = sig.param_types(&ft);
                if sig.variadic {
                    ps.push("...".into());
                }
                let nr = if gd.noreturn { " noreturn" } else { "" };
                format!("declare {} {}({}){nr}", sig.ret_type(), quote_sym(&s), ps.join(", "))
            } else {
                let tl = if gd.thread_local { "thread_local " } else { "" };
                format!(
                    "{} = external {tl}global {}, align {}",
                    quote_sym(&s),
                    mem_ty(gd.ty.ty),
                    align_of(gd.ty.ty)
                )
            };
            self.decls.insert(s.clone(), decl);
        }
        quote_sym(&s)
    }

    fn string_sym(&mut self, s: u32) -> String {
        self.used_strings.insert(s);
        format!("@.str.{s}")
    }

    fn emit_global(&mut self, g: global_id) {
        let gd = self.prog.globals[g as usize].clone();
        let size = size_of(gd.ty.ty);
        let init =
            gd.init.clone().unwrap_or(const_data { bytes: vec![0; size as usize], relocs: vec![] });
        let linkage = match gd.linkage {
            LinkageInternal => "internal ",
            LinkageExternal => "",
        };
        let kind = if gd.ty.is_const()
            && !gd.ty.kind().eq(&TypeKindError)
            && !has_mutable_member(gd.ty.ty)
        {
            "constant"
        } else {
            "global"
        };
        let tl = if gd.thread_local { "thread_local " } else { "" };
        let (ty, val) = self.const_image(&init, size);
        let _ = writeln!(
            self.globals_out,
            "{} = {linkage}{tl}{kind} {ty} {val}, align {}",
            quote_sym(&gd.symbol),
            align_of(gd.ty.ty).max(1)
        );
    }

    /// An LLVM constant for a byte image with relocations.
    fn const_image(&mut self, d: &const_data, size: u64) -> (String, String) {
        let mut bytes = d.bytes.clone();
        bytes.resize(size as usize, 0);
        if d.relocs.is_empty() {
            if bytes.iter().all(|b| *b == 0) {
                return (format!("[{size} x i8]"), "zeroinitializer".into());
            }
            return (format!("[{size} x i8]"), llvm_bytes(&bytes));
        }
        let mut relocs = d.relocs.clone();
        relocs.sort_by_key(|r| r.offset);
        let mut tys = Vec::new();
        let mut vals = Vec::new();
        let mut pos = 0u64;
        for r in &relocs {
            if r.offset > pos {
                let chunk = &bytes[pos as usize..r.offset as usize];
                tys.push(format!("[{} x i8]", chunk.len()));
                vals.push(format!("[{} x i8] {}", chunk.len(), llvm_bytes(chunk)));
            }
            let target = match r.target {
                RelocTargetGlobal(g) => self.global_sym(g),
                RelocTargetString(s) => self.string_sym(s),
            };
            let v = if r.addend == 0 {
                target
            } else {
                format!("getelementptr (i8, ptr {target}, i64 {})", r.addend)
            };
            tys.push("ptr".into());
            vals.push(format!("ptr {v}"));
            pos = r.offset + 8;
        }
        if pos < size {
            let chunk = &bytes[pos as usize..];
            tys.push(format!("[{} x i8]", chunk.len()));
            vals.push(format!("[{} x i8] {}", chunk.len(), llvm_bytes(chunk)));
        }
        (format!("<{{ {} }}>", tys.join(", ")), format!("<{{ {} }}>", vals.join(", ")))
    }

    fn intrinsic(&mut self, name: &str, decl: &str) {
        self.intrinsics.entry(name.to_string()).or_insert_with(|| decl.to_string());
    }

    fn emit_function(&mut self, b: &body) {
        let gd = self.prog.globals[b.func as usize].clone();
        let ft = func_of(gd.ty.ty).unwrap();
        let sig = lower_sig(&ft);
        let mut fe =
            fn_emitter { cg: self, b, sig, ft, lines: Vec::new(), tmp: 0, traps: Vec::new() };
        let text = fe.emit(&gd);
        self.funcs_out.push_str(&text);
    }
}

fn has_mutable_member(t: type_id) -> bool {
    match kind(t) {
        TypeKindRecord(r) => record(r)
            .fields
            .iter()
            .any(|f| !f.ty.is_const() && false || has_mutable_member(f.ty.ty)),
        _ => false,
    }
}

struct fn_emitter<'a, 'b> {
    cg: &'a mut codegen<'b>,
    b: &'a body,
    sig: lowered_sig,
    ft: func_type,
    lines: Vec<String>,
    tmp: u32,
    traps: Vec<(String, usize)>,
}

impl fn_emitter<'_, '_> {
    fn t(&mut self) -> String {
        self.tmp += 1;
        format!("%t{}", self.tmp)
    }

    fn label(&mut self) -> String {
        self.tmp += 1;
        format!("L{}", self.tmp)
    }

    fn line(&mut self, s: String) {
        self.lines.push(format!("  {s}"));
    }

    fn start_block(&mut self, l: &str) {
        self.lines.push(format!("{l}:"));
    }

    fn local_ptr(l: local) -> String {
        format!("%l{l}")
    }

    fn emit(&mut self, gd: &global_decl) -> String {
        let prog = self.cg.prog;
        let linkage = match gd.linkage {
            LinkageInternal => "internal ",
            LinkageExternal if gd.inline_ && !gd.exported => "linkonce_odr ",
            LinkageExternal => "",
        };
        let ptys = self.sig.param_types(&self.ft);
        let mut params = Vec::new();
        for (i, p) in ptys.iter().enumerate() {
            params.push(format!("{p} %a{i}"));
        }
        if self.sig.variadic {
            params.push("...".into());
        }
        let nr = if gd.noreturn { " noreturn" } else { "" };
        let header = format!(
            "define {linkage}{} {}({}){nr} {{",
            self.sig.ret_type(),
            quote_sym(&gd.symbol),
            params.join(", ")
        );
        self.lines.push("entry:".into());
        for (i, l) in self.b.locals.iter().enumerate() {
            if is_void(l.ty.ty) {
                continue;
            }
            let ty = mem_ty(l.ty.ty);
            self.line(format!("%l{i} = alloca {ty}, align {}", align_of(l.ty.ty).max(1)));
        }
        for (i, l) in self.b.locals.iter().enumerate() {
            if l.zero_init && !is_void(l.ty.ty) {
                self.memset(&Self::local_ptr(i as local), size_of(l.ty.ty));
            }
        }
        self.store_params();
        self.line("br label %bb0".into());
        for (i, bb) in self.b.blocks.iter().enumerate() {
            self.start_block(&format!("bb{i}"));
            for s in &bb.stmts {
                self.statement(s);
            }
            self.terminator(&bb.term, bb.term_span);
        }
        for (label, msg) in std::mem::take(&mut self.traps) {
            self.start_block(&label);
            let len = self.cg.trap_msgs[msg].len();
            self.line(format!("call void @crust.trap(ptr @.trapmsg.{msg}, i64 {len})"));
            self.line("unreachable".into());
        }
        let _ = prog;
        let mut out = header;
        out.push('\n');
        for l in &self.lines {
            out.push_str(l);
            out.push('\n');
        }
        out.push_str("}\n\n");
        out
    }

    fn store_params(&mut self) {
        let mut arg = 0usize;
        if matches!(self.sig.ret, ArgKindMemory) {
            arg = 1;
        }
        let kinds = self.sig.params.clone();
        for (i, k) in kinds.iter().enumerate() {
            let l = (i + 1) as local;
            let dst = Self::local_ptr(l);
            let pt = self.ft.params[i].ty;
            match k {
                ArgKindIgnore => {}
                ArgKindDirect(t, _) => {
                    self.line(format!(
                        "store {t} %a{arg}, ptr {dst}, align {}",
                        align_of(pt).max(1)
                    ));
                    arg += 1;
                }
                ArgKindExpand(ps) => {
                    for (pty, off, _) in ps {
                        let p = self.gep(&dst, *off);
                        self.line(format!("store {pty} %a{arg}, ptr {p}, align 1"));
                        arg += 1;
                    }
                }
                ArgKindMemory => {
                    self.memcpy(&dst, &format!("%a{arg}"), size_of(pt));
                    arg += 1;
                }
            }
        }
    }

    fn gep(&mut self, base: &str, off: u64) -> String {
        if off == 0 {
            return base.to_string();
        }
        let r = self.t();
        self.line(format!("{r} = getelementptr i8, ptr {base}, i64 {off}"));
        r
    }

    fn memcpy(&mut self, dst: &str, src: &str, size: u64) {
        self.cg.intrinsic("memcpy", "declare void @llvm.memcpy.p0.p0.i64(ptr, ptr, i64, i1)");
        self.line(format!(
            "call void @llvm.memcpy.p0.p0.i64(ptr {dst}, ptr {src}, i64 {size}, i1 false)"
        ));
    }

    fn memset(&mut self, dst: &str, size: u64) {
        self.cg.intrinsic("memset", "declare void @llvm.memset.p0.i64(ptr, i8, i64, i1)");
        self.line(format!("call void @llvm.memset.p0.i64(ptr {dst}, i8 0, i64 {size}, i1 false)"));
    }

    fn place_ty(&self, p: &place) -> qual_type {
        self.b.place_ty(p, self.cg.prog)
    }

    fn operand_ty(&self, op: &Operand) -> qual_type {
        match op {
            OperandCopy(p) | OperandMove(p) => self.place_ty(p),
            OperandConst(c) => match c {
                ConstInt(_, t) | ConstFloat(_, t) | ConstNull(t) => q(*t),
                ConstGlobalAddr(g) => q(pointer_to(self.cg.prog.globals[*g as usize].ty)),
                ConstStringAddr(_) => q(pointer_to(q(char_()))),
            },
        }
    }

    /// The address of a place. Bit-fields return the storage unit's address.
    fn place_addr(&mut self, p: &place) -> String {
        let mut addr = match &p.base {
            PlaceBaseLocal(l) => Self::local_ptr(*l),
            PlaceBaseGlobal(g) => self.cg.global_sym(*g),
            PlaceBaseString(s) => self.cg.string_sym(*s),
        };
        let mut t = match &p.base {
            PlaceBaseLocal(l) => self.b.locals[*l as usize].ty,
            PlaceBaseGlobal(g) => self.cg.prog.globals[*g as usize].ty,
            PlaceBaseString(s) => q(self.cg.prog.strings[*s as usize].ty),
        };
        for pr in &p.proj {
            match pr {
                ProjDeref => {
                    let r = self.t();
                    self.line(format!("{r} = load ptr, ptr {addr}, align 8"));
                    addr = r;
                }
                ProjField(rec, i) => {
                    let off = with_record(*rec, |r| r.fields[*i as usize].offset);
                    addr = self.gep(&addr, off);
                }
                ProjConstIndex(i) => {
                    let et = proj_ty(t, pr);
                    if let TypeKindSlice { .. } = t.kind() {
                        let r = self.t();
                        self.line(format!("{r} = load ptr, ptr {addr}, align 8"));
                        addr = r;
                    }
                    addr = self.gep(&addr, i * size_of(et.ty));
                }
                ProjIndex(l) => {
                    let et = proj_ty(t, pr);
                    if let TypeKindSlice { .. } = t.kind() {
                        let r = self.t();
                        self.line(format!("{r} = load ptr, ptr {addr}, align 8"));
                        addr = r;
                    }
                    let iv = self.t();
                    self.line(format!("{iv} = load i64, ptr %l{l}, align 8"));
                    let off = self.t();
                    self.line(format!("{off} = mul i64 {iv}, {}", size_of(et.ty)));
                    let r = self.t();
                    self.line(format!("{r} = getelementptr i8, ptr {addr}, i64 {off}"));
                    addr = r;
                }
            }
            t = proj_ty(t, pr);
        }
        addr
    }

    fn bitfield_of(&self, p: &place) -> Option<bit_field> {
        match p.proj.last() {
            Some(ProjField(r, i)) => with_record(*r, |rd| rd.fields[*i as usize].bits.clone()),
            _ => None,
        }
    }

    /// Loads a scalar from a place, as its in-register LLVM value.
    fn load_place(&mut self, p: &place) -> String {
        let t = self.place_ty(p).ty;
        let addr = self.place_addr(p);
        let lt = llvm_scalar(t);
        if let Some(bf) = self.bitfield_of(p) {
            let raw = self.t();
            self.line(format!("{raw} = load {lt}, ptr {addr}, align 1"));
            let bits = size_of(t) * 8;
            let shl = bits as u32 - bf.shift - bf.width;
            let a = self.t();
            self.line(format!("{a} = shl {lt} {raw}, {shl}"));
            let r = self.t();
            let sh = if is_signed(t) { "ashr" } else { "lshr" };
            self.line(format!("{r} = {sh} {lt} {a}, {}", bits as u32 - bf.width));
            return r;
        }
        let r = self.t();
        let vol = if self.place_ty(p).quals & QualVolatile != 0 { "volatile " } else { "" };
        self.line(format!("{r} = load {vol}{lt}, ptr {addr}, align {}", align_of(t).max(1)));
        r
    }

    fn store_place(&mut self, p: &place, v: &str) {
        let t = self.place_ty(p).ty;
        let addr = self.place_addr(p);
        let lt = llvm_scalar(t);
        if let Some(bf) = self.bitfield_of(p) {
            let raw = self.t();
            self.line(format!("{raw} = load {lt}, ptr {addr}, align 1"));
            let bits = size_of(t) * 8;
            let mask: u128 = if bf.width as u64 >= bits {
                u128::MAX
            } else {
                ((1u128 << bf.width) - 1) << bf.shift
            };
            let mask =
                wrap_to(mask as i128, int_of(to_unsigned(int_kind(t).unwrap_or(IntKindUInt))));
            let fmask = wrap_to(mask, t);
            let nmask = wrap_to(!mask, t);
            let shifted = self.t();
            self.line(format!("{shifted} = shl {lt} {v}, {}", bf.shift));
            let m1 = self.t();
            self.line(format!("{m1} = and {lt} {shifted}, {fmask}"));
            let cleared = self.t();
            self.line(format!("{cleared} = and {lt} {raw}, {nmask}"));
            let r = self.t();
            self.line(format!("{r} = or {lt} {cleared}, {m1}"));
            self.line(format!("store {lt} {r}, ptr {addr}, align 1"));
            return;
        }
        let vol = if self.place_ty(p).quals & QualVolatile != 0 { "volatile " } else { "" };
        self.line(format!("store {vol}{lt} {v}, ptr {addr}, align {}", align_of(t).max(1)));
    }

    fn const_value(&mut self, c: &Constant) -> String {
        match c {
            ConstInt(v, t) => {
                if is_pointer(*t) {
                    if *v == 0 { "null".into() } else { format!("inttoptr (i64 {v} to ptr)") }
                } else if is_float(*t) {
                    float_lit(*v as f64, *t)
                } else {
                    wrap_to(*v, *t).to_string()
                }
            }
            ConstFloat(f, t) => float_lit(*f, *t),
            ConstNull(t) => {
                if is_float(*t) {
                    float_lit(0.0, *t)
                } else if is_integer(*t) {
                    "0".into()
                } else {
                    "null".into()
                }
            }
            ConstGlobalAddr(g) => self.cg.global_sym(*g),
            ConstStringAddr(s) => self.cg.string_sym(*s),
        }
    }

    fn operand_value(&mut self, op: &Operand) -> String {
        match op {
            OperandCopy(p) | OperandMove(p) => self.load_place(p),
            OperandConst(c) => self.const_value(c),
        }
    }

    fn operand_addr(&mut self, op: &Operand) -> String {
        match op {
            OperandCopy(p) | OperandMove(p) => self.place_addr(p),
            OperandConst(_) => diag::ice("aggregate constant operand"),
        }
    }

    /// Converts an `i1` to the in-memory form of `t`.
    fn widen_i1(&mut self, v: &str, t: type_id) -> String {
        let lt = llvm_scalar(t);
        let r = self.t();
        self.line(format!("{r} = zext i1 {v} to {lt}"));
        r
    }

    fn as_i1(&mut self, v: &str, t: type_id) -> String {
        let r = self.t();
        if is_float(t) {
            self.line(format!("{r} = fcmp une {} {v}, {}", llvm_scalar(t), float_lit(0.0, t)));
        } else if llvm_scalar(t) == "ptr" {
            self.line(format!("{r} = icmp ne ptr {v}, null"));
        } else {
            self.line(format!("{r} = icmp ne {} {v}, 0", llvm_scalar(t)));
        }
        r
    }

    fn statement(&mut self, s: &statement) {
        match &s.kind {
            StatementAssign(p, rv) => self.assign(p, rv),
            StatementStorageLive(_) | StatementStorageDead(_) | StatementNop => {}
            StatementDropIfInit(_) => diag::ice("drop elaboration left a conditional drop"),
            StatementDrop(p) => {
                let a = self.place_addr(p);
                let t = self.place_ty(p).ty;
                self.drop_value(&a, t);
            }
            StatementDropIfFlag(p, flag) => {
                let f = self.t();
                self.line(format!("{f} = load i8, ptr %l{flag}, align 1"));
                let c = self.t();
                self.line(format!("{c} = icmp ne i8 {f}, 0"));
                let (yes, no) = (self.label(), self.label());
                self.line(format!("br i1 {c}, label %{yes}, label %{no}"));
                self.start_block(&yes);
                let a = self.place_addr(p);
                let t = self.place_ty(p).ty;
                self.drop_value(&a, t);
                self.line(format!("store i8 0, ptr %l{flag}, align 1"));
                self.line(format!("br label %{no}"));
                self.start_block(&no);
            }
            StatementSetFlag(l, v) => {
                self.line(format!("store i8 {}, ptr %l{l}, align 1", *v as u8))
            }
            StatementCall { dest, func, args, .. } => self.call(dest.as_ref(), func, args),
            StatementAssert(c, k) => {
                let v = self.operand_value(c);
                let ct = self.operand_ty(c).ty;
                let b = self.as_i1(&v, ct);
                let ok = self.label();
                let trap = self.label();
                let (l, col) =
                    if s.span.is_dummy() { (0, 0) } else { diag::line_col(s.span.file, s.span.lo) };
                let file = if s.span.is_dummy() {
                    String::new()
                } else {
                    diag::file(s.span.file).display.clone()
                };
                let what = match k {
                    AssertKindBounds => "index out of bounds",
                    AssertKindDivZero => "division by zero",
                };
                let msg = format!("crust: {what} at {file}:{l}:{col}\n");
                self.cg.trap_msgs.push(msg);
                self.cg.need_trap = true;
                let id = self.cg.trap_msgs.len() - 1;
                self.traps.push((trap.clone(), id));
                self.line(format!(
                    "br i1 {b}, label %{ok}, label %{trap}, !prof !{{!\"branch_weights\", i32 2000, i32 1}}"
                ));
                self.start_block(&ok);
            }
            StatementVaStart(ap) => {
                self.cg.intrinsic("va_start", "declare void @llvm.va_start(ptr)");
                let v = self.operand_value(ap);
                self.line(format!("call void @llvm.va_start(ptr {v})"));
            }
            StatementVaEnd(ap) => {
                self.cg.intrinsic("va_end", "declare void @llvm.va_end(ptr)");
                let v = self.operand_value(ap);
                self.line(format!("call void @llvm.va_end(ptr {v})"));
            }
            StatementVaCopy(d, s2) => {
                self.cg.intrinsic("va_copy", "declare void @llvm.va_copy(ptr, ptr)");
                let a = self.operand_value(d);
                let b = self.operand_value(s2);
                self.line(format!("call void @llvm.va_copy(ptr {a}, ptr {b})"));
            }
        }
    }

    /// Calls the drop function of an owned value, then drops its owned members.
    fn drop_value(&mut self, addr: &str, t: type_id) {
        match kind(t) {
            TypeKindRecord(r) => {
                let rd = record(r);
                if let Some(d) = &rd.drop {
                    let sym = quote_sym(&d.symbol);
                    if !self.cg.defined.contains(&d.symbol) {
                        self.cg
                            .decls
                            .entry(d.symbol.clone())
                            .or_insert_with(|| format!("declare void {sym}(ptr)"));
                    }
                    self.line(format!("call void {sym}(ptr {addr})"));
                }
                for f in &rd.fields {
                    if is_owned(f.ty.ty) {
                        let fa = self.gep(addr, f.offset);
                        self.drop_value(&fa, f.ty.ty);
                    }
                }
            }
            TypeKindArray(e, Some(n)) => {
                if !is_owned(e.ty) {
                    return;
                }
                let sz = size_of(e.ty);
                for i in 0..n {
                    let ea = self.gep(addr, i * sz);
                    self.drop_value(&ea, e.ty);
                }
            }
            _ => {}
        }
    }

    fn assign(&mut self, p: &place, rv: &Rvalue) {
        let dt = self.place_ty(p).ty;
        if is_void(dt) {
            return;
        }
        if is_aggregate(dt) {
            let dst = self.place_addr(p);
            match rv {
                RvalueUse(op) | RvalueCast(_, op, _) => {
                    let src = self.operand_addr(op);
                    self.memcpy(&dst, &src, size_of(dt));
                }
                RvalueZero => self.memset(&dst, size_of(dt)),
                RvalueArrayToSlice(op, n) => {
                    let ptr = self.operand_value(op);
                    self.line(format!("store ptr {ptr}, ptr {dst}, align 8"));
                    let lp = self.gep(&dst, 8);
                    self.line(format!("store i64 {n}, ptr {lp}, align 8"));
                }
                RvalueVaArg(ap) => {
                    let a = self.operand_value(ap);
                    if !matches!(classify(dt), ArgKindMemory) {
                        diag::error(
                            "CR1301",
                            self.b.span,
                            "`va_arg` of a struct passed in registers is not supported in Crust 0.1.0",
                        );
                        return;
                    }
                    let src = self.va_arg_addr(&a, dt);
                    self.memcpy(&dst, &src, size_of(dt));
                }
                _ => diag::ice(format!("unsupported aggregate rvalue {rv:?}")),
            }
            return;
        }
        let v = self.rvalue(rv, dt);
        self.store_place(p, &v);
    }

    fn rvalue(&mut self, rv: &Rvalue, dt: type_id) -> String {
        let dl = llvm_scalar(dt);
        match rv {
            RvalueUse(op) => {
                let v = self.operand_value(op);
                let st = self.operand_ty(op).ty;
                if llvm_scalar(st) != dl {
                    return self.convert(&v, st, dt);
                }
                v
            }
            RvalueZero => {
                if is_float(dt) {
                    float_lit(0.0, dt)
                } else if dl == "ptr" {
                    "null".into()
                } else {
                    "0".into()
                }
            }
            RvalueBinary(op, a, b) => self.binary(*op, a, b, dt),
            RvalueUnary(op, a) => {
                let v = self.operand_value(a);
                let at = self.operand_ty(a).ty;
                let al = llvm_scalar(at);
                match op {
                    UnOpNeg if is_float(at) => {
                        let r = self.t();
                        self.line(format!("{r} = fneg {al} {v}"));
                        r
                    }
                    UnOpNeg => {
                        let r = self.t();
                        self.line(format!("{r} = sub {al} 0, {v}"));
                        r
                    }
                    UnOpBitNot => {
                        let r = self.t();
                        self.line(format!("{r} = xor {al} {v}, -1"));
                        r
                    }
                    UnOpNot => {
                        let b = self.as_i1(&v, at);
                        let n = self.t();
                        self.line(format!("{n} = xor i1 {b}, true"));
                        self.widen_i1(&n, dt)
                    }
                    _ => v,
                }
            }
            RvalueCast(k, op, to) => {
                let v = self.operand_value(op);
                let from = self.operand_ty(op).ty;
                self.cast(*k, &v, from, to.ty)
            }
            RvaluePtrAdd(p, i) => {
                let pv = self.operand_value(p);
                let iv = self.operand_value(i);
                let pt = self.operand_ty(p).ty;
                let es = pointee(pt).map(|e| size_of(e.ty)).unwrap_or(1);
                let off = self.t();
                self.line(format!("{off} = mul i64 {iv}, {es}"));
                let r = self.t();
                self.line(format!("{r} = getelementptr i8, ptr {pv}, i64 {off}"));
                r
            }
            RvaluePtrDiff(a, b) => {
                let av = self.operand_value(a);
                let bv = self.operand_value(b);
                let es = pointee(self.operand_ty(a).ty).map(|e| size_of(e.ty)).unwrap_or(1).max(1);
                let (x, y, d, r) = (self.t(), self.t(), self.t(), self.t());
                self.line(format!("{x} = ptrtoint ptr {av} to i64"));
                self.line(format!("{y} = ptrtoint ptr {bv} to i64"));
                self.line(format!("{d} = sub i64 {x}, {y}"));
                self.line(format!("{r} = sdiv i64 {d}, {es}"));
                r
            }
            RvalueAddrOf(p) | RvalueRef(_, p) => self.place_addr(p),
            RvalueSliceLen(p) => {
                let a = self.place_addr(p);
                let lp = self.gep(&a, 8);
                let r = self.t();
                self.line(format!("{r} = load i64, ptr {lp}, align 8"));
                r
            }
            RvalueVaArg(ap) => {
                let a = self.operand_value(ap);
                let addr = self.va_arg_addr(&a, dt);
                let r = self.t();
                self.line(format!("{r} = load {dl}, ptr {addr}, align 1"));
                r
            }
            RvalueArrayToSlice(..) => diag::ice("slice into a scalar"),
        }
    }

    fn binary(&mut self, op: BinOp, a: &Operand, b: &Operand, dt: type_id) -> String {
        let at = self.operand_ty(a).ty;
        let av = self.operand_value(a);
        let bv = self.operand_value(b);
        let al = llvm_scalar(at);
        let r = self.t();
        if op.is_comparison() {
            let pred = if is_float(at) {
                match op {
                    BinOpLt => "fcmp olt",
                    BinOpGt => "fcmp ogt",
                    BinOpLe => "fcmp ole",
                    BinOpGe => "fcmp oge",
                    BinOpEq => "fcmp oeq",
                    _ => "fcmp une",
                }
            } else {
                let s = is_signed(at) && al != "ptr";
                match (op, s) {
                    (BinOpLt, true) => "icmp slt",
                    (BinOpLt, false) => "icmp ult",
                    (BinOpGt, true) => "icmp sgt",
                    (BinOpGt, false) => "icmp ugt",
                    (BinOpLe, true) => "icmp sle",
                    (BinOpLe, false) => "icmp ule",
                    (BinOpGe, true) => "icmp sge",
                    (BinOpGe, false) => "icmp uge",
                    (BinOpEq, _) => "icmp eq",
                    _ => "icmp ne",
                }
            };
            self.line(format!("{r} = {pred} {al} {av}, {bv}"));
            return self.widen_i1(&r, dt);
        }
        if is_float(at) {
            let i = match op {
                BinOpAdd => "fadd",
                BinOpSub => "fsub",
                BinOpMul => "fmul",
                BinOpDiv => "fdiv",
                _ => "frem",
            };
            self.line(format!("{r} = {i} {al} {av}, {bv}"));
            return r;
        }
        let signed = is_signed(at);
        let i = match op {
            BinOpAdd => "add",
            BinOpSub => "sub",
            BinOpMul => "mul",
            BinOpDiv => {
                if signed {
                    "sdiv"
                } else {
                    "udiv"
                }
            }
            BinOpRem => {
                if signed {
                    "srem"
                } else {
                    "urem"
                }
            }
            BinOpBitAnd => "and",
            BinOpBitOr => "or",
            BinOpBitXor => "xor",
            BinOpShl | BinOpShr => {
                // Shift counts are taken modulo the width, so an oversized
                // shift gives a defined value instead of poison.
                let bt = self.operand_ty(b).ty;
                let bl = llvm_scalar(bt);
                let bits = size_of(at) * 8;
                let cnt = self.t();
                self.line(format!("{cnt} = and {bl} {bv}, {}", bits - 1));
                let cnt2 = if bl != al { self.int_resize(&cnt, bt, at) } else { cnt };
                let ins = if op == BinOpShl {
                    "shl"
                } else if signed {
                    "ashr"
                } else {
                    "lshr"
                };
                self.line(format!("{r} = {ins} {al} {av}, {cnt2}"));
                return r;
            }
            _ => "add",
        };
        if matches!(op, BinOpDiv | BinOpRem) && signed {
            // INT_MIN / -1 overflows; compute it as wrapping.
            let neg1 = self.t();
            self.line(format!("{neg1} = icmp eq {al} {bv}, -1"));
            let safe_b = self.t();
            self.line(format!("{safe_b} = select i1 {neg1}, {al} 1, {al} {bv}"));
            let q2 = self.t();
            self.line(format!("{q2} = {i} {al} {av}, {safe_b}"));
            let negv = self.t();
            if op == BinOpDiv {
                self.line(format!("{negv} = sub {al} 0, {av}"));
            } else {
                self.line(format!("{negv} = add {al} 0, 0"));
            }
            self.line(format!("{r} = select i1 {neg1}, {al} {negv}, {al} {q2}"));
            return r;
        }
        self.line(format!("{r} = {i} {al} {av}, {bv}"));
        r
    }

    /// The address of the next variadic argument of type `t`, following the
    /// x86-64 System V `va_arg` algorithm. LLVM's own `va_arg` instruction is
    /// not reliable at -O0, so the access is expanded here, as clang does.
    fn va_arg_addr(&mut self, ap: &str, t: type_id) -> String {
        let k = classify(t);
        let (in_reg, sse) = match &k {
            ArgKindDirect(lt, _) => match lt.as_str() {
                "x86_fp80" => (false, false),
                "float" | "double" => (true, true),
                _ => (true, false),
            },
            _ => (false, false),
        };
        let size = size_of(t).max(1);
        let align = align_of(t).max(8);
        let mem_label = self.label();
        let done = self.label();
        let over_p = self.gep(ap, 8);
        let mut reg_addr = None;
        let reg_label = self.label();
        if in_reg {
            let (off_p, limit, step) =
                if sse { (self.gep(ap, 4), 160, 16) } else { (ap.to_string(), 40, 8) };
            let off = self.t();
            self.line(format!("{off} = load i32, ptr {off_p}, align 4"));
            let fits = self.t();
            self.line(format!("{fits} = icmp ule i32 {off}, {limit}"));
            self.line(format!("br i1 {fits}, label %{reg_label}, label %{mem_label}"));
            self.start_block(&reg_label);
            let save_p = self.gep(ap, 16);
            let save = self.t();
            self.line(format!("{save} = load ptr, ptr {save_p}, align 8"));
            let off64 = self.t();
            self.line(format!("{off64} = zext i32 {off} to i64"));
            let a = self.t();
            self.line(format!("{a} = getelementptr i8, ptr {save}, i64 {off64}"));
            let next = self.t();
            self.line(format!("{next} = add i32 {off}, {step}"));
            self.line(format!("store i32 {next}, ptr {off_p}, align 4"));
            self.line(format!("br label %{done}"));
            reg_addr = Some(a);
        } else {
            self.line(format!("br label %{mem_label}"));
        }
        self.start_block(&mem_label);
        let over = self.t();
        self.line(format!("{over} = load ptr, ptr {over_p}, align 8"));
        let aligned = if align > 8 {
            let i = self.t();
            self.line(format!("{i} = ptrtoint ptr {over} to i64"));
            let j = self.t();
            self.line(format!("{j} = add i64 {i}, {}", align - 1));
            let m = self.t();
            self.line(format!("{m} = and i64 {j}, {}", -(align as i64)));
            let p = self.t();
            self.line(format!("{p} = inttoptr i64 {m} to ptr"));
            p
        } else {
            over
        };
        let bump = self.t();
        self.line(format!(
            "{bump} = getelementptr i8, ptr {aligned}, i64 {}",
            size.div_ceil(8) * 8
        ));
        self.line(format!("store ptr {bump}, ptr {over_p}, align 8"));
        self.line(format!("br label %{done}"));
        self.start_block(&done);
        let r = self.t();
        match reg_addr {
            Some(a) => self
                .line(format!("{r} = phi ptr [ {a}, %{reg_label} ], [ {aligned}, %{mem_label} ]")),
            None => self.line(format!("{r} = phi ptr [ {aligned}, %{mem_label} ]")),
        }
        r
    }

    fn int_resize(&mut self, v: &str, from: type_id, to: type_id) -> String {
        let (fs, ts) = (size_of(from), size_of(to));
        if fs == ts {
            return v.to_string();
        }
        let r = self.t();
        let (fl, tl) = (llvm_scalar(from), llvm_scalar(to));
        if ts < fs {
            self.line(format!("{r} = trunc {fl} {v} to {tl}"));
        } else if is_signed(from) {
            self.line(format!("{r} = sext {fl} {v} to {tl}"));
        } else {
            self.line(format!("{r} = zext {fl} {v} to {tl}"));
        }
        r
    }

    fn convert(&mut self, v: &str, from: type_id, to: type_id) -> String {
        let k = match (is_float(from), is_float(to)) {
            (true, true) => CastKindFloatToFloat,
            (true, false) => CastKindFloatToInt,
            (false, true) => CastKindIntToFloat,
            _ if llvm_scalar(from) == "ptr" && llvm_scalar(to) != "ptr" => CastKindPtrToInt,
            _ if llvm_scalar(from) != "ptr" && llvm_scalar(to) == "ptr" => CastKindIntToPtr,
            _ => CastKindIntToInt,
        };
        self.cast(k, v, from, to)
    }

    fn cast(&mut self, k: CastKind, v: &str, from: type_id, to: type_id) -> String {
        let (fl, tl) = (llvm_scalar(from), llvm_scalar(to));
        let r = self.t();
        match k {
            CastKindToBool => {
                let b = self.as_i1(v, from);
                return self.widen_i1(&b, to);
            }
            CastKindIntToInt => {
                if matches!(kind(to), TypeKindBool) {
                    let b = self.as_i1(v, from);
                    return self.widen_i1(&b, to);
                }
                return self.int_resize(v, from, to);
            }
            CastKindIntToFloat => {
                let i = if is_signed(from) { "sitofp" } else { "uitofp" };
                self.line(format!("{r} = {i} {fl} {v} to {tl}"));
            }
            CastKindFloatToInt => {
                if matches!(kind(to), TypeKindBool) {
                    let b = self.as_i1(v, from);
                    return self.widen_i1(&b, to);
                }
                // Saturating conversion: out-of-range values give a defined result.
                let s = if is_signed(to) { "fptosi" } else { "fptoui" };
                let name = format!("llvm.{s}.sat.{tl}.{}", llvm_float_suffix(fl));
                self.cg.intrinsic(&name, &format!("declare {tl} @{name}({fl})"));
                self.line(format!("{r} = call {tl} @{name}({fl} {v})"));
            }
            CastKindFloatToFloat => {
                if size_of(from) == size_of(to) && fl == tl {
                    return v.to_string();
                }
                let rank = |s: &str| match s {
                    "float" => 0,
                    "double" => 1,
                    _ => 2,
                };
                let i = if rank(tl) > rank(fl) { "fpext" } else { "fptrunc" };
                self.line(format!("{r} = {i} {fl} {v} to {tl}"));
            }
            CastKindPtrToInt => {
                if matches!(kind(to), TypeKindBool) {
                    let b = self.as_i1(v, from);
                    return self.widen_i1(&b, to);
                }
                self.line(format!("{r} = ptrtoint ptr {v} to {tl}"));
            }
            CastKindIntToPtr => {
                self.line(format!("{r} = inttoptr {fl} {v} to ptr"));
            }
            CastKindNullToPtr => return "null".into(),
            CastKindToVoid => return "undef".into(),
            _ => {
                if fl != tl {
                    return self.convert(v, from, to);
                }
                return v.to_string();
            }
        }
        r
    }

    fn call(&mut self, dest: Option<&place>, func: &Operand, args: &[Operand]) {
        let fty = self.operand_ty(func).ty;
        let ft = func_of(fty).unwrap_or_else(|| diag::ice("call of a non-function"));
        let sig = lower_sig(&ft);
        let callee = self.operand_value(func);
        let mut av = Vec::new();
        let ret_mem = matches!(sig.ret, ArgKindMemory);
        let sret_tmp = if ret_mem {
            let size = size_of(ft.ret.ty);
            let a = self.t();
            self.line(format!("{a} = alloca [{size} x i8], align {}", align_of(ft.ret.ty).max(1)));
            av.push(format!("ptr sret([{size} x i8]) align {} {a}", align_of(ft.ret.ty)));
            Some(a)
        } else {
            None
        };
        // Variadic arguments are classified like parameters of their own type.
        let mut all_tys: Vec<type_id> = ft.params.iter().map(|p| p.ty).collect();
        for a in args.iter().skip(ft.params.len()) {
            all_tys.push(self.operand_ty(a).ty);
        }
        let kinds = classify_params(&all_tys, ret_mem);
        for (i, a) in args.iter().enumerate() {
            let at = all_tys[i];
            match &kinds[i] {
                ArgKindIgnore => {}
                ArgKindDirect(t, ext) => {
                    let mut v = self.operand_value(a);
                    let ot = self.operand_ty(a).ty;
                    if llvm_scalar(ot) != t.as_str() {
                        v = self.convert(&v, ot, at);
                    }
                    let e = ext.map(|e| format!(" {e}")).unwrap_or_default();
                    av.push(format!("{t}{e} {v}"));
                }
                ArgKindExpand(ps) => {
                    let base = self.operand_addr(a);
                    for (pty, off, _) in ps {
                        let p = self.gep(&base, *off);
                        let r = self.t();
                        self.line(format!("{r} = load {pty}, ptr {p}, align 1"));
                        av.push(format!("{pty} {r}"));
                    }
                }
                ArgKindMemory => {
                    let src = self.operand_addr(a);
                    let size = size_of(at);
                    let tmp = self.t();
                    self.line(format!(
                        "{tmp} = alloca [{size} x i8], align {}",
                        align_of(at).max(8)
                    ));
                    self.memcpy(&tmp, &src, size);
                    av.push(format!(
                        "ptr byval([{size} x i8]) align {} {tmp}",
                        align_of(at).max(8)
                    ));
                }
            }
        }
        let fn_ty = if sig.variadic { sig.fn_type(&ft) } else { ret_llvm(&sig.ret) };
        let call = format!("call {fn_ty} {callee}({})", av.join(", "));
        let rl = ret_llvm(&sig.ret);
        if rl == "void" {
            self.line(call);
            if let (Some(d), Some(tmp)) = (dest, sret_tmp) {
                let da = self.place_addr(d);
                self.memcpy(&da, &tmp, size_of(ft.ret.ty));
            }
            return;
        }
        let r = self.t();
        self.line(format!("{r} = {call}"));
        let Some(d) = dest else { return };
        match &sig.ret {
            ArgKindDirect(..) => self.store_place(d, &r),
            ArgKindExpand(ps) => {
                let da = self.place_addr(d);
                if ps.len() == 1 {
                    self.line(format!("store {} {r}, ptr {da}, align 1", ps[0].0));
                } else {
                    for (i, (pty, off, _)) in ps.iter().enumerate() {
                        let e = self.t();
                        self.line(format!("{e} = extractvalue {rl} {r}, {i}"));
                        let p = self.gep(&da, *off);
                        self.line(format!("store {pty} {e}, ptr {p}, align 1"));
                    }
                }
            }
            _ => {}
        }
    }

    fn terminator(&mut self, t: &Terminator, _sp: crate::diag::span) {
        match t {
            TermGoto(b) => self.line(format!("br label %bb{b}")),
            TermSwitch(op, cases, d) => {
                let v = self.operand_value(op);
                let ot = self.operand_ty(op).ty;
                let lt = llvm_scalar(ot);
                let arms: Vec<String> = cases
                    .iter()
                    .map(|(c, b)| format!("{lt} {}, label %bb{b}", wrap_to(*c, ot)))
                    .collect();
                self.line(format!("switch {lt} {v}, label %bb{d} [ {} ]", arms.join(" ")));
            }
            TermUnreachable => self.line("unreachable".into()),
            TermTrap => {
                self.cg.intrinsic("trap", "declare void @llvm.trap() noreturn nounwind");
                self.line("call void @llvm.trap()".into());
                self.line("unreachable".into());
            }
            TermReturn => self.ret(),
        }
    }

    fn ret(&mut self) {
        let rt = self.ft.ret.ty;
        let ret = self.sig.ret.clone();
        match ret {
            ArgKindIgnore => self.line("ret void".into()),
            ArgKindMemory => {
                self.memcpy("%a0", "%l0", size_of(rt));
                self.line("ret void".into());
            }
            ArgKindDirect(t, _) => {
                let r = self.t();
                self.line(format!("{r} = load {t}, ptr %l0, align {}", align_of(rt).max(1)));
                self.line(format!("ret {t} {r}"));
            }
            ArgKindExpand(ps) => {
                let rl = ret_llvm(&ArgKindExpand(ps.clone()));
                if ps.len() == 1 {
                    let r = self.t();
                    self.line(format!("{r} = load {}, ptr %l0, align 1", ps[0].0));
                    self.line(format!("ret {rl} {r}"));
                    return;
                }
                let mut agg = "undef".to_string();
                for (i, (pty, off, _)) in ps.iter().enumerate() {
                    let p = self.gep("%l0", *off);
                    let v = self.t();
                    self.line(format!("{v} = load {pty}, ptr {p}, align 1"));
                    let n = self.t();
                    self.line(format!("{n} = insertvalue {rl} {agg}, {pty} {v}, {i}"));
                    agg = n;
                }
                self.line(format!("ret {rl} {agg}"));
            }
        }
    }
}

fn llvm_float_suffix(t: &str) -> &'static str {
    match t {
        "float" => "f32",
        "double" => "f64",
        _ => "f80",
    }
}
