// C headers for `[[crust::c_abi]]` exports (docs/ABI.md, section 4). The
// header holds only C23: struct and enum definitions the signatures need,
// then the declarations.
use super::*;
use crate::sema::types::*;
use std::collections::HashSet;
use std::path::Path;

struct header_gen {
    defs: String,
    done_records: HashSet<u32>,
    done_enums: HashSet<u32>,
}

impl header_gen {
    fn need(&mut self, t: type_id, by_value: bool) {
        match kind(t) {
            TypeKindPointer(p) => self.need(p.ty, false),
            TypeKindArray(e, _) => self.need(e.ty, by_value),
            TypeKindFunction(f) => {
                self.need(f.ret.ty, true);
                for p in &f.params {
                    self.need(p.ty, true);
                }
            }
            TypeKindEnum(e) => {
                if self.done_enums.insert(e) {
                    let ed = enum_info(e);
                    let Some(tag) = ed.tag else { return };
                    let vals: Vec<String> =
                        ed.enumerators.iter().map(|(n, v)| format!("    {n} = {v},")).collect();
                    let fixed = if ed.fixed {
                        format!(" : {}", int_name(ed.underlying))
                    } else {
                        String::new()
                    };
                    self.defs
                        .push_str(&format!("enum {tag}{fixed} {{\n{}\n}};\n\n", vals.join("\n")));
                }
            }
            TypeKindRecord(r) => {
                let rd = record(r);
                let Some(tag) = rd.tag else { return };
                let kw = if rd.is_union { "union" } else { "struct" };
                if !by_value || !rd.complete {
                    if !self.done_records.contains(&r) {
                        self.defs.push_str(&format!("{kw} {tag};\n"));
                    }
                    return;
                }
                if !self.done_records.insert(r) {
                    return;
                }
                for f in &rd.fields {
                    self.need(f.ty.ty, true);
                }
                let mut b = format!("{kw} {tag} {{\n");
                for f in &rd.fields {
                    let n = f.name.map(|n| n.to_string()).unwrap_or_default();
                    let width =
                        f.bits.as_ref().map(|b| format!(" : {}", b.width)).unwrap_or_default();
                    b.push_str(&format!("    {}{width};\n", display_decl(f.ty, &n)));
                }
                b.push_str("};\n\n");
                self.defs.push_str(&b);
            }
            _ => {}
        }
    }
}

fn guard_name(module: &str) -> String {
    let mut s = String::from("CRUST_");
    for c in module.chars() {
        s.push(if c.is_ascii_alphanumeric() { c.to_ascii_uppercase() } else { '_' });
    }
    s.push_str("_H");
    s
}

/// The generated header for one module.
pub fn generate(i: &module_interface, src: &Path) -> String {
    let mut g = header_gen {
        defs: String::new(),
        done_records: HashSet::new(),
        done_enums: HashSet::new(),
    };
    let mut decls = String::new();
    for e in &i.exports {
        match &e.kind {
            ExportKindFunc { ty, c_abi: true, symbol, noreturn, .. } => {
                g.need(ty.ty, true);
                let nr = if *noreturn { "[[noreturn]] " } else { "" };
                decls.push_str(&format!("{nr}{};\n", display_decl(*ty, symbol)));
            }
            ExportKindVar { ty, c_abi: true, symbol, .. } => {
                g.need(ty.ty, true);
                decls.push_str(&format!("extern {};\n", display_decl(*ty, symbol)));
            }
            _ => {}
        }
    }
    let guard = guard_name(i.name.as_str());
    format!(
        "/**\n* Ko, (Baczynski-Bruce) 2026; Apache 2.0\n*/\n\
         /* Generated by crust {} from {}. Do not edit. */\n\
         #ifndef {guard}\n#define {guard}\n\n\
         #include <stddef.h>\n\n\
         #ifdef __cplusplus\nextern \"C\" {{\n#endif\n\n\
         {}{}\n\
         #ifdef __cplusplus\n}}\n#endif\n\n#endif\n",
        env!("CARGO_PKG_VERSION"),
        src.display(),
        g.defs,
        decls
    )
}
